const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const path=require('node:path');
const base=process.env.REVIEW_TEST_WEB_URL||'';
if(process.env.REVIEW_TEST_FIXTURES!=='1'||!/^http:\/\/localhost:\d+$/.test(base))throw Error('Disposable localhost test environment required');
const php=process.env.REVIEW_TEST_PHP;
const fixture=path.resolve(__dirname,'../../backend/tests/seed_history.php');
const cleanup=path.resolve(__dirname,'../../backend/tests/cleanup_monitoring.php');
(async()=>{
 const id=execFileSync(php,[fixture],{encoding:'utf8'}).trim();
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try {
  const context=await browser.newContext({viewport:{width:1440,height:1050}});
  const token=await(await context.request.get(base+'/auth/csrf.php')).json();
  await context.request.post(base+'/auth/login.php',{headers:{'X-CSRF-Token':token.csrf_token},data:{email:'officer@review.test',password:'Review-Test-Only-2026!'}});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/#/monitoring');
  const section=page.locator('.ecological-history');
  await section.getByRole('heading',{name:'Historical data & trends'}).waitFor();
  await section.getByLabel('History species',{exact:true}).selectOption(id);
  await section.getByLabel('Start date').fill('2026-10-10');await section.getByLabel('End date').fill('2026-10-13');
  await section.getByRole('button',{name:'Apply range'}).click();
  await section.locator('.history-metrics article').first().getByText('55',{exact:true}).waitFor();
  assert.equal(await section.locator('svg circle').count(),3);
  // One segment for adjacent 10th/11th; no invented line across the missing 12th.
  assert.equal(await section.locator('svg line[stroke-width="3"]').count(),1);
  await section.getByLabel('Trend metric').selectOption('humidity');
  assert.match(await section.locator('svg').getAttribute('aria-label'),/Humidity.*%/);
  await section.getByText('View trend data table',{exact:true}).click();
  assert.equal(await section.locator('details tbody tr').count(),3);
  await section.getByRole('button',{name:'Next',exact:true}).click();
  await section.getByText('Page 2 of 2 · 50 measurements per page',{exact:true}).waitFor();
  assert.equal(await section.locator(':scope > .table-scroll tbody tr').count(),5);
  await section.getByLabel('Start date').fill('2026-10-12');await section.getByLabel('End date').fill('2026-10-12');
  assert(await section.getByRole('button',{name:'Previous',exact:true}).isDisabled());
  await section.getByRole('button',{name:'Apply range'}).click();
  await section.getByText('No measurements in this date range. Try another range or species.',{exact:true}).waitFor();
  assert.equal(await section.locator('svg').count(),0);
  await section.getByLabel('Start date').fill('2025-01-01');await section.getByLabel('End date').fill('2027-01-01');
  await section.getByRole('button',{name:'Apply range'}).click();
  await section.getByText('Monthly averages · Gaps indicate missing measurements.',{exact:true}).waitFor();
  await page.route('**/api/get_monitoring_history.php?**',r=>r.fulfill({status:503,json:{error:'Test outage'}}));
  await section.getByRole('button',{name:'Apply range'}).click();
  await section.getByRole('alert').getByText('History could not be loaded. Please retry. Previous results are still displayed.',{exact:true}).waitFor();
  assert.equal(await section.locator('svg circle').count(),1);
  await page.unroute('**/api/get_monitoring_history.php?**');
  await section.getByLabel('Start date').fill('2026-10-10');await section.getByLabel('End date').fill('2026-10-13');
  await section.getByRole('button',{name:'Apply range'}).click();
  await section.locator('.history-metrics article').first().getByText('55',{exact:true}).waitFor();
  await page.evaluate(()=>document.activeElement?.blur());
  await section.scrollIntoViewIfNeeded();
  if(process.env.HISTORY_SCREENSHOT_DIR)await section.screenshot({path:path.join(process.env.HISTORY_SCREENSHOT_DIR,'monitoring-history-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  if(process.env.HISTORY_SCREENSHOT_DIR)await section.screenshot({path:path.join(process.env.HISTORY_SCREENSHOT_DIR,'monitoring-history-mobile.png')});
  assert.deepEqual(errors,[]);
  console.log('PASS real history browser: date/species filters, daily/monthly chart, missing-data gap, metric switch, pagination, empty results, failure retention/recovery and 390px layout. Fictional fixture data only.');
 }finally{await browser.close();execFileSync(php,[cleanup,id])}
})().catch(e=>{console.error(e);process.exit(1)});
